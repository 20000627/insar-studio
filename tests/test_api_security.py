"""Security headers and CSP hardening (P2-2)."""

from __future__ import annotations

from pathlib import Path

import insar_studio.api as api_module
from insar_studio.jobs import JobManager
from insar_studio.project import ProjectStore


def _client(tmp_path: Path, monkeypatch):
    store = ProjectStore(tmp_path / "projects")
    monkeypatch.setattr(api_module, "ProjectStore", lambda: store)
    monkeypatch.setattr(api_module, "ensure_runtime_dirs", lambda: None)
    monkeypatch.setattr(api_module, "JobManager", lambda: JobManager(tmp_path / "jobs"))
    app = api_module.create_app()
    app.config.update(TESTING=True)
    return app.test_client(), store


def test_security_headers_on_page_and_api(tmp_path, monkeypatch):
    client, _ = _client(tmp_path, monkeypatch)

    for path in ("/", "/api/health", "/api/projects"):
        response = client.get(path)
        assert response.status_code == 200
        assert response.headers["X-Content-Type-Options"] == "nosniff"
        assert response.headers["X-Frame-Options"] == "DENY"
        assert response.headers["Referrer-Policy"] == "no-referrer"
        assert "camera=()" in response.headers["Permissions-Policy"]

        csp = response.headers["Content-Security-Policy"]
        assert "script-src 'self'" in csp
        assert "object-src 'none'" in csp
        assert "frame-ancestors 'none'" in csp
        # Inline style attributes are still generated by app.js, but scripts
        # must never be allowed to run inline.
        script_policy = csp.split("script-src", 1)[1].split(";", 1)[0]
        assert "unsafe-inline" not in script_policy


def test_api_responses_are_not_cached(tmp_path, monkeypatch):
    client, _ = _client(tmp_path, monkeypatch)

    response = client.get("/api/projects")

    assert response.headers["Cache-Control"] == "no-store"


def test_static_template_has_no_inline_handlers_or_scripts():
    root = Path(api_module.__file__).parent
    html = (root / "templates" / "index.html").read_text(encoding="utf-8")
    script = (root / "static" / "js" / "app.js").read_text(encoding="utf-8")

    for token in ("onclick=", "onerror=", "onload=", "<script>"):
        assert token not in html
        assert token not in script
    assert "<script src=" in html
