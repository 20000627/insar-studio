SCHEMA = "insar-studio/project/v1"
TECHNIQUES = ("sbas", "ps", "ds", "dinsar")
#: Parameters whose sensible value depends on the selected technique.  They
#: are restored to that route's defaults when the route changes, unless the
#: caller explicitly provided a new value in the same request.
ROUTE_PARAM_KEYS = (
    "multilook",
    "max_temporal_baseline",
    "max_pairs",
    "ps_star_all",
    "ds_patch",
    "ds_overlap",
)


def route_defaults(technique: str) -> dict[str, Any]:
    defaults = _default_params(str(technique).lower())
    return {key: defaults[key] for key in ROUTE_PARAM_KEYS if key in defaults}


STAGE_ORDER = ("coregistration", "network", "interferometry", "atmosphere", "inversion")

# Products owned by the inversion.  Arrays, rasters, tables and reports all
# depend on the final unwrapped stack, so a rerun must remove them before the
# new result is written.
_INVERSION_PRODUCTS = (
    "products/arrays",
    "products/geotiff",
    "products/csv",
    "products/report",
    "products/exports",
    "products/inversion.json",
    "products/validation.json",
    "products/figures/velocity.png",
    "products/figures/dem_error.png",
    "products/figures/temporal_coherence.png",
    "products/figures/residual.png",
    "products/figures/timeseries_peak.png",
    "products/figures/ps_candidates.png",
    "products/figures/dinsar_displacement.png",
    "products/figures/dinsar_coherence.png",
    "products/figures/dinsar_wrapped.png",
)
# Atmospheric correction feeds the inversion only; the network, DS
# phase-linking and coregistration diagnostics above it stay valid.
_ATMOSPHERE_PRODUCTS = ("data/atmosphere", "products/figures/atmosphere.png") + _INVERSION_PRODUCTS
# New interferograms invalidate the atmosphere and the inversion, but not the
# network figure or the coregistration diagnostics.  The DS phase-linking
# coherence figure is produced together with the interferograms and is
# regenerated by the DS interferometry stage, so it is removed here.
_INTERFEROMETRY_PRODUCTS = (
    "interferograms",
    "products/figures/ds_coherence.png",
) + _ATMOSPHERE_PRODUCTS
# A rebuilt network invalidates everything below it.  The coregistration
# figures are independent of the pair selection and remain valid.
_NETWORK_PRODUCTS = ("data/network.json", "products/figures/network.png") + _INTERFEROMETRY_PRODUCTS

#: Per-stage products that become stale when the stage is rebuilt.  Each tuple
#: lists only the artefacts owned by that stage and its downstream stages;
#: figures from still-valid upstream stages are preserved.  Deleting the whole
#: ``products`` tree at every stage made a full rerun silently lose the
#: network, atmosphere and coregistration diagnostics from the results page
#: and the report.
_STAGE_ARTIFACTS: dict[str, tuple[str, ...]] = {
    "coregistration": ("data/processed", "data/network.json", "interferograms", "data/atmosphere", "products"),
    "network": _NETWORK_PRODUCTS,
    "interferometry": _INTERFEROMETRY_PRODUCTS,
    "atmosphere": _ATMOSPHERE_PRODUCTS,
    "inversion": _INVERSION_PRODUCTS,
}
#: Number of bounded retries used when Windows reports a transient lock or a
#: directory that was repopulated while it was being deleted.
_REMOVE_ATTEMPTS = 6
_REMOVE_BACKOFF_SECONDS = 0.05
_TRASH_DIRNAME = ".trash"


def _remove_artifact(target: Path, trash_dir: Path) -> None:
    """Delete one stale artifact without racing concurrent writers.

    ``/api/projects/<id>/results`` can rewrite ``products/validation.json``
    while a new job starts.  Deleting the tree in place makes Windows raise
    ``WinError 145`` (directory not empty) when the directory is repopulated
    between enumeration and ``os.rmdir``.  Renaming the tree into a private
    trash directory first gives such a writer a fresh live path, so the stale
    tree is removed in isolation.  The bounded retry covers transient handles
    held by readers or antivirus; a persistent error is still raised.
    """
    if not target.is_dir():
        for attempt in range(_REMOVE_ATTEMPTS):
            try:
                target.unlink()
                return
            except FileNotFoundError:
                return
            except OSError:
                if attempt == _REMOVE_ATTEMPTS - 1:
                    raise
                time.sleep(_REMOVE_BACKOFF_SECONDS * (attempt + 1))

    trash_dir.mkdir(parents=True, exist_ok=True)
    staged = trash_dir / f"{target.name}-{uuid.uuid4().hex}"
    try:
        os.replace(target, staged)
    except FileNotFoundError:
        return
    except OSError:
        # The tree cannot be renamed (for example a reader holds a handle
        # without delete sharing); retry the in-place delete instead.
        staged = target
    for attempt in range(_REMOVE_ATTEMPTS):
        try:
            shutil.rmtree(staged)
            break
        except FileNotFoundError:
            break
        except OSError:
            if attempt == _REMOVE_ATTEMPTS - 1:
                raise
            time.sleep(_REMOVE_BACKOFF_SECONDS * (attempt + 1))
    # Best effort: another purge may still be using the same trash directory.
    try:
        trash_dir.rmdir()
    except OSError:
        pass


def purge_downstream(project_root: Path | str, stage: str) -> list[str]:
    """Remove products that a rerun of ``stage`` is about to invalidate.

    The engine must never leave older interferograms, atmospheric corrections,
    or inversion products behind when an upstream stage is rebuilt.  This is
    intentionally separate from :meth:`ProjectStore.reset_derived`: the latter
    clears everything, while this helper preserves the stages that are still
    valid upstream of the requested one.
    """
    stage = str(stage).lower()
    if stage not in STAGE_ORDER:
        raise ValueError(f"未知处理阶段: {stage}")
    root = Path(project_root)
    index = STAGE_ORDER.index(stage)
    trash_dir = root / _TRASH_DIRNAME
    removed: list[str] = []
    for relative in _STAGE_ARTIFACTS[stage]:
        target = root / relative
        if not target.exists():
            continue
        _remove_artifact(target, trash_dir)
        removed.append(relative)
    project_path = root / "project.json"
    project = read_json(project_path, {}) or {}
    steps = project.get("steps_run")
    if isinstance(steps, dict):
        for key in STAGE_ORDER[index:]:
            steps.pop(key, None)
        steps.pop("pipeline", None)
        project["updated_at"] = time.strftime("%Y-%m-%d %H:%M:%S")
        atomic_write_json(project_path, project)
    return removed


def _as_dict(value: Any) -> dict[str, Any]:
    return value if isinstance(value, dict) else {}


def _stack_n_dates(path: Path) -> int | None:
    meta = _as_dict(read_json(Path(path) / "data" / "stack" / "meta.json", {}))
    try:
        value = int(meta.get("n_dates") or 0)
    except (TypeError, ValueError):
        return None
    return value or None


def _default_params(technique: str) -> dict[str, Any]:
    params = dict(DEFAULT_PROCESSING)
    if technique == "ps":
        params.update({"multilook": 1, "max_temporal_baseline": 96, "max_pairs": 140, "ps_star_all": True})
    elif technique == "ds":
        params.update({"multilook": 2, "ds_patch": 9, "max_temporal_baseline": 72})
    elif technique == "dinsar":
        params.update({"multilook": 2, "remove_ramp": True})
    return params


class ProjectStore:
    def __init__(self, root: Path | None = None) -> None:
        self.root = Path(root or PROJECTS_DIR)
        self.root.mkdir(parents=True, exist_ok=True)

    def path(self, project_id: str) -> Path:
        if not project_id or any(ch not in "abcdefghijklmnopqrstuvwxyz0123456789_" for ch in project_id.lower()):
            raise ValueError("非法项目编号")
        path = (self.root / project_id).resolve()
        if self.root.resolve() not in path.parents:
            raise ValueError("项目路径越界")
        return path

    def create(
        self,
        name: str,
        technique: str = "sbas",
        *,
        params: dict[str, Any] | None = None,
        source: str = "demo",
        notes: str = "",
    ) -> dict[str, Any]:
        project_id = new_project_id()
        technique = str(technique).lower()
        if technique not in TECHNIQUES:
            raise ValueError(f"未知技术路线: {technique}")
        path = self.path(project_id)
        path.mkdir(parents=True, exist_ok=False)
        cleaned = validate_params(params or {}, technique=technique)
        now = time.strftime("%Y-%m-%d %H:%M:%S")
        project = {
            "schema": SCHEMA,
            "id": project_id,
            "name": name.strip()[:120] or "未命名项目",
            "technique": technique,
            "source": source,
            "demo": source == "demo",
            "notes": notes[:20000],
            "created_at": now,
            "updated_at": now,
            "params": public_params({**_default_params(technique), **cleaned}),
            "tags": [],
            "steps_run": {},
        }
        atomic_write_json(path / "project.json", project)
        return project

    def create_demo(self, name: str, technique: str = "sbas", params: dict[str, Any] | None = None) -> dict[str, Any]:
        project = self.create(name, technique, params=params, source="demo")
        path = self.path(project["id"])
        meta = generate_demo_dataset(path)
        project["stack"] = {
            "rows": meta["rows"],
            "cols": meta["cols"],
            "n_dates": meta["n_dates"],
            "dates": meta["dates"],
            "platform": meta["platform"],
            "source": "demo",
        }
        project["updated_at"] = time.strftime("%Y-%m-%d %H:%M:%S")
        atomic_write_json(path / "project.json", project)
        return project

    def get(self, project_id: str) -> dict[str, Any]:
        path = self.path(project_id)
        project = read_json(path / "project.json")
        if not isinstance(project, dict) or not project:
            raise FileNotFoundError("项目不存在")
        return project

    def save(self, project: dict[str, Any]) -> dict[str, Any]:
        project["updated_at"] = time.strftime("%Y-%m-%d %H:%M:%S")
        if isinstance(project.get("params"), dict):
            project["params"] = public_params(project["params"])
        atomic_write_json(self.path(project["id"]) / "project.json", project)
        return project

    def update(self, project_id: str, patch: dict[str, Any]) -> dict[str, Any]:
        project = self.get(project_id)
        old_technique = str(project.get("technique", "sbas")).lower()
        target_technique = str(patch.get("technique") or old_technique).lower()
        explicit_params = patch.get("params") if isinstance(patch.get("params"), dict) else {}
        if explicit_params:
            explicit_params = validate_params(
                explicit_params,
                technique=target_technique,
                n_dates=_stack_n_dates(self.path(project_id)),
            )
        technique_changed = False
        for key, value in patch.items():
            if key in ("id", "created_at", "schema"):
                continue
            if key == "params" and isinstance(value, dict):
                project["params"] = public_params({**project.get("params", {}), **explicit_params})
            elif key == "name":
                project[key] = str(value).strip()[:120] or "未命名项目"
            elif key == "notes":
                project[key] = str(value)[:20000]
            elif key == "tags":
                if not isinstance(value, list):
                    raise ValueError("标签必须是数组")
                project[key] = [str(tag)[:40] for tag in value[:20]]
            else:
                if key == "technique":
                    technique = str(value).lower()
                    if technique not in TECHNIQUES:
                        raise ValueError(f"未知技术路线: {technique}")
                    if technique != old_technique:
                        technique_changed = True
                        # Switching route should also restore that route's sensible
                        # sampling defaults, unless the caller set them explicitly.
                        for pkey, pvalue in route_defaults(technique).items():
                            if pkey not in explicit_params:
                                project.setdefault("params", {})[pkey] = pvalue
                    project[key] = technique
                else:
                    project[key] = value
        saved = self.save(project)
        if technique_changed:
            # Interferograms, network and products belong to the previous
            # route.  Keeping them would show a "completed" project whose
            # products cannot be reproduced with the selected technique.
            saved = self.reset_derived(project_id, keep_coreg=True)
        return saved

    def list(self) -> list[dict[str, Any]]:
        out = []
        for directory in sorted(self.root.iterdir(), key=lambda p: p.stat().st_mtime, reverse=True):
            if not directory.is_dir():
                continue
            project = read_json(directory / "project.json")
            if not isinstance(project, dict) or not project:
                continue
            out.append(self._summary_row(project, directory))
        return out

    def _summary_row(self, project: dict[str, Any], path: Path) -> dict[str, Any]:
        project_id = str(project.get("id") or path.name)
        status = self.status(project_id, project)
        size = 0
        for p in path.rglob("*"):
            try:
                if p.is_file():
                    size += p.stat().st_size
            except OSError:
                pass
        row = {
            "id": project_id,
            "name": str(project.get("name") or "未命名项目"),
            "technique": project.get("technique", "sbas"),
            "demo": bool(project.get("demo")),
            "created_at": project.get("created_at", ""),
            "updated_at": project.get("updated_at", ""),
            "steps_done": sum(1 for s in status if s["done"]),
            "steps_total": len(status),
            "stale": any(s.get("stale") for s in status),
            "size_bytes": size,
            "size_human": format_bytes(size),
            "status": status,
        }
        stack_meta = _as_dict(read_json(path / "data" / "stack" / "meta.json", {}))
        if stack_meta:
            dates = stack_meta.get("dates")
            dates = dates if isinstance(dates, list) and dates else []
            row["n_dates"] = stack_meta.get("n_dates")
            row["dates"] = [dates[0] if dates else None, dates[-1] if dates else None]
            row["rows"] = stack_meta.get("rows")
            row["cols"] = stack_meta.get("cols")
        inv = _as_dict(read_json(path / "products" / "inversion.json", {}))
        if inv:
            row["velocity_median"] = inv.get("velocity_median_mm_yr")
            row["valid_fraction"] = inv.get("valid_fraction")
            row["technique_used"] = inv.get("technique")
        return row

    def status(self, project_id: str, project: dict[str, Any] | None = None) -> list[dict[str, Any]]:
        path = self.path(project_id)
        project = project or self.get(project_id)
        # Jobs are always executed with the engine defaults merged in, even
        # when a project was created by an older release that did not persist
        # every default key.  Compare against the same effective parameter set
        # so hidden defaults do not look like user edits.
        technique = str(project.get("technique", "sbas")).lower()
        raw_params = _as_dict(project.get("params"))
        try:
            params = validate_params(
                merge_params(raw_params, {}),
                technique=technique,
            )
        except Exception:
            params = merge_params(raw_params, {})
        params = with_atmosphere_defaults(params, demo=bool(project.get("demo")))
        steps_run = _as_dict(project.get("steps_run"))

        stack_meta = _as_dict(read_json(path / "data" / "stack" / "meta.json", {}))
        coreg = _as_dict(read_json(path / "data" / "processed" / "coreg.json", {}))
        network = _as_dict(read_json(path / "data" / "network.json", {}))
        ifg = _as_dict(read_json(path / "interferograms" / "summary.json", {}))
        atm = _as_dict(read_json(path / "data" / "atmosphere" / "atmosphere.json", {}))
        inv = _as_dict(read_json(path / "products" / "inversion.json", {}))

        def is_stale(key: str) -> bool:
            record = steps_run.get(key) if isinstance(steps_run, dict) else None
            if not isinstance(record, dict):
                return False
            stored = record.get("params_hash")
            if not stored:
                return False
            try:
                # Coregistration is route-independent and is recorded without
                # a technique label by the engine.  Including one here would
                # mark every network/ifg/result stale after a fresh run.
                stage_technique = None if key in ("coregistration", "atmosphere") else technique
                current = fingerprint(params, stage=key, technique=stage_technique)
            except Exception:
                return False
            return str(stored) != current

        coreg_exists = bool((path / "data" / "processed" / "slc_coreg.npy").exists())
        coreg_stale = coreg_exists and is_stale("coregistration")
        network_exists = bool(network.get("pairs"))
        network_stale = network_exists and (coreg_stale or is_stale("network"))
        ifg_exists = bool(ifg.get("n_pairs"))
        ifg_stale = ifg_exists and (network_stale or is_stale("interferometry"))
        atm_exists = bool(atm)
        atm_stale = atm_exists and (ifg_stale or is_stale("atmosphere"))
        inv_exists = bool(inv)
        inv_stale = inv_exists and (atm_stale or is_stale("inversion"))

        def detail(key: str, default: str) -> str:
            if key == "network":
                if not network_exists:
                    return "未构建"
                if coreg_stale:
                    return "配准参数已变更，需重跑"
                if is_stale("network"):
                    return "网络参数已变更，需重跑"
                return f"{len(network.get('pairs', []))} 对"
            if key == "interferometry":
                if not ifg_exists:
                    return "未处理"
                if ifg_stale:
                    return "上游参数已变更，需重跑"
                return f"{ifg.get('n_pairs', 0)} 对"
            if key == "atmosphere":
                if not atm_exists:
                    return "未处理"
                if atm_stale:
                    return "上游参数已变更，需重跑"
                return {"gacos": "GACOS", "empirical": "经验校正", "off": "未校正"}.get(atm.get("method", ""), "已处理")
            if key == "inversion":
                if not inv_exists:
                    return "未反演"
                if inv_stale:
                    return "参数已变更，需重跑"
                return str(inv.get("technique", "")).upper()
            if key == "results":
                if not inv_exists:
                    return "待生成"
                if inv_stale:
                    return "反演参数已变更"
                return "可导出"
            return default

        steps = [
            {"key": "project", "label": "项目", "done": True, "stale": False, "detail": "已建档"},
            {"key": "data", "label": "数据", "done": bool(stack_meta), "stale": False, "detail": f"{stack_meta.get('n_dates', 0)} 景" if stack_meta else "未建档"},
            {"key": "network", "label": "网络", "done": network_exists and not network_stale, "stale": network_stale, "detail": detail("network", "未构建")},
            {"key": "interferometry", "label": "干涉", "done": ifg_exists and not ifg_stale, "stale": ifg_stale, "detail": detail("interferometry", "未处理")},
            {"key": "atmosphere", "label": "大气", "done": atm_exists and not atm_stale, "stale": atm_stale, "detail": detail("atmosphere", "未处理")},
            {"key": "inversion", "label": "反演", "done": inv_exists and not inv_stale, "stale": inv_stale, "detail": detail("inversion", "未反演")},
            {"key": "results", "label": "成果", "done": inv_exists and not inv_stale, "stale": inv_stale, "detail": detail("results", "待生成")},
        ]
        return steps

    def reset_derived(self, project_id: str, *, keep_coreg: bool = True) -> dict[str, Any]:
        """Remove derived products while keeping the source stack intact.

        This is the supported recovery path for stale or corrupted products,
        and is also used when the technique changes.
        """
        path = self.path(project_id)
        project = self.get(project_id)
        for rel in ("interferograms", "products", "data/atmosphere"):
            target = path / rel
            if target.exists():
                shutil.rmtree(target, ignore_errors=False)
        network_file = path / "data" / "network.json"
        if network_file.exists():
            network_file.unlink()
        processed = path / "data" / "processed"
        if processed.exists():
            ds_ref = processed / "ds_reference.json"
            if ds_ref.exists():
                ds_ref.unlink()
            if not keep_coreg:
                shutil.rmtree(processed, ignore_errors=False)
        keep_steps = {"project", "data", "coregistration"} if keep_coreg else {"project", "data"}
        project["steps_run"] = {
            key: value
            for key, value in _as_dict(project.get("steps_run")).items()
            if key in keep_steps
        }
        project = self.save(project)
        # Pair previews are cached globally by project name.
        cache = path.parents[1] / "cache" / "figures"
        if cache.exists():
            for cached in cache.glob(f"{path.name}_*"):
                try:
                    cached.unlink()
                except OSError:
                    pass
        return project

    def overview(self, project_id: str) -> dict[str, Any]:
        path = self.path(project_id)
        project = self.get(project_id)
        status = self.status(project_id, project)
        stack_meta = _as_dict(read_json(path / "data" / "stack" / "meta.json", {}))
        coreg = _as_dict(read_json(path / "data" / "processed" / "coreg.json", {}))
        network = _as_dict(read_json(path / "data" / "network.json", {}))
        ifg = _as_dict(read_json(path / "interferograms" / "summary.json", {}))
        atm = _as_dict(read_json(path / "data" / "atmosphere" / "atmosphere.json", {}))
        inv = _as_dict(read_json(path / "products" / "inversion.json", {}))
        assets = {}
        for key, rel in (
            ("amplitude", "data/preview_amplitude.png"),
            ("network", "products/figures/network.png"),
            ("velocity", "products/figures/velocity.png"),
            ("dem_error", "products/figures/dem_error.png"),
            ("temporal_coherence", "products/figures/temporal_coherence.png"),
            ("residual", "products/figures/residual.png"),
            ("atmosphere", "products/figures/atmosphere.png"),
            ("coreg_gain", "products/figures/coreg_coherence_gain.png"),
            ("ps", "products/figures/ps_candidates.png"),
            ("ds", "products/figures/ds_coherence.png"),
            ("dinsar", "products/figures/dinsar_displacement.png"),
        ):
            if (path / rel).exists():
                assets[key] = rel
        dates = stack_meta.get("dates", [])
        return {
            "project": project,
            "status": status,
            "stack": stack_meta,
            "dates": dates,
            "n_dates": len(dates),
            "coreg": coreg,
            "network": {k: v for k, v in network.items() if k != "pairs"},
            "pairs": network.get("pairs", []),
            "interferometry": ifg,
            "atmosphere": atm,
            "inversion": inv,
            "assets": assets,
            "truth_available": (path / "data" / "stack" / "truth.npz").exists(),
            "files": self.product_files(project_id),
        }

    def product_files(self, project_id: str) -> list[dict[str, Any]]:
        path = self.path(project_id)
        products = path / "products"
        out = []
        if not products.exists():
            return out
        for p in sorted(products.rglob("*")):
            if p.suffix.lower() not in (".tif", ".tiff", ".png", ".csv", ".json", ".md", ".docx", ".zip", ".npy"):
                continue
            try:
                if not p.is_file():
                    continue
                size = p.stat().st_size
                relative = p.relative_to(path)
                parts = p.relative_to(products).parts
                group = parts[0] if len(parts) > 1 else "root"
            except (OSError, ValueError):
                # A running job can remove a product between directory
                # enumeration and stat().  Such a file is simply no longer part
                # of the result set; it must not turn the whole project into a
                # misleading 404.
                continue
            out.append(
                {
                    "path": str(relative).replace("\\", "/"),
                    "name": p.name,
                    "size": size,
                    "group": group,
                }
            )
        return out

    def delete(self, project_id: str) -> None:
        path = self.path(project_id)
        if path.exists():
            shutil.rmtree(path, ignore_errors=False)

    def stack_preview(self, project_id: str) -> dict[str, Any]:
        path = self.path(project_id)
        stack_meta = read_json(path / "data" / "stack" / "meta.json", {}) or {}
        out: dict[str, Any] = {"meta": stack_meta}
        try:
            stack = load_stack(path)
            step = max(1, stack.n_dates // 10)
            amp = np.asarray([np.abs(stack.slc[i]).mean() for i in range(0, stack.n_dates, step)]) if stack.n_dates else []
            dem = stack.dem
            out["amplitude_mean"] = [float(x) for x in amp]
            out["dem_range"] = [float(np.nanmin(dem)), float(np.nanmax(dem))]
            out["mask_fraction"] = float(np.asarray(stack.mask, dtype=bool).mean())
        except Exception as exc:
            out["error"] = str(exc)
        return out
