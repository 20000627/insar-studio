        if busy:
            return busy
        root = store.path(project_id)
        payload = _json_body() if request.is_json else None
        if payload is not None:
            urls = _list_field(payload.get("urls"))
            paths = _list_field(payload.get("paths"), newline_only=True)
        else:
            urls = _list_field(request.form.get("urls"))
            paths = _list_field(request.form.get("paths"), newline_only=True)
        upload_root: Path | None = None
        uploads = []
        if not request.is_json:
            uploads = request.files.getlist("files") + request.files.getlist("file")
            uploads = [item for item in uploads if item and item.filename]
        if uploads:
            if len(uploads) > GACOS_MAX_IMPORT_FILES:
                return _json_error(f"一次最多上传 {GACOS_MAX_IMPORT_FILES} 个文件", 400)
            upload_root = root / "data" / "gacos" / ".tmp" / f"upload_{uuid.uuid4().hex[:10]}"
            upload_root.mkdir(parents=True, exist_ok=True)
            total = 0
            try:
                for index, item in enumerate(uploads):
                    # Each upload gets its own directory so identical names are
                    # preserved for provenance without overwriting each other.
                    target = upload_root / f"item{index:03d}" / _safe_upload_name(item.filename or "")
                    target.parent.mkdir(parents=True, exist_ok=True)
                    item.save(target)
                    total += target.stat().st_size
                    if total > GACOS_MAX_UPLOAD_BYTES:
                        shutil.rmtree(upload_root, ignore_errors=True)
                        limit = GACOS_MAX_UPLOAD_BYTES // (1024 * 1024)
                        return _json_error(f"上传内容超过 {limit} MiB 上限，请分次导入", 413)
                    paths.append(str(target))
            except OSError as exc:
                shutil.rmtree(upload_root, ignore_errors=True)
                return _json_error(f"保存上传文件失败: {exc}", 500)
        if not urls and not paths:
            if upload_root is not None:
                shutil.rmtree(upload_root, ignore_errors=True)
            return _json_error("请提供 GACOS 邮件下载链接、本地路径，或上传 tar.gz/产品文件", 400)
        try:
            result = import_gacos_sources(root, urls=urls, paths=paths)
        except Exception as exc:
            return _json_error(str(exc), 500)
        finally:
            if upload_root is not None:
                shutil.rmtree(upload_root, ignore_errors=True)
        return jsonify(result)

