    @app.after_request
    def security_headers(response):
        # The server is meant for a local workstation, but the same headers make
        # an accidental LAN deployment much less dangerous: no MIME sniffing, no
        # framing, no referrer leakage and no inline script execution.
        response.headers.setdefault("X-Content-Type-Options", "nosniff")
        response.headers.setdefault("X-Frame-Options", "DENY")
        response.headers.setdefault("Referrer-Policy", "no-referrer")
        response.headers.setdefault(
            "Permissions-Policy", "camera=(), microphone=(), geolocation=()"
        )
        response.headers.setdefault("Content-Security-Policy", CONTENT_SECURITY_POLICY)
        if request.path.startswith("/api/"):
            # Project metadata, job logs and credentials in request bodies must
            # not be retained by browser or proxy caches.
            response.headers["Cache-Control"] = "no-store"
        return response

