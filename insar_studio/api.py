class ApiInputError(Exception):
    """A malformed or unacceptable request body, mapped to a 4xx response."""

    def __init__(self, message: str, status: int = 400) -> None:
        super().__init__(message)
        self.message = message
        self.status = status


def _max_json_bytes() -> int:
    override = parse_size(os.environ.get("INSAR_MAX_JSON_BYTES", ""))
    return override or DEFAULT_MAX_JSON_BYTES


def _json_body(*, optional: bool = True) -> dict[str, Any]:
    """Read a JSON object body with explicit content-type and size checks.

    ``request.get_json(silent=True)`` turns broken JSON into ``None``, which
    used to make some endpoints continue with empty defaults (and, for project
    creation, actually create a project).  Every JSON endpoint now goes through
    this function so a malformed request fails loudly with 400 instead.
    """
    limit = _max_json_bytes()
    declared = request.content_length
    if declared is not None and declared > limit:
        raise ApiInputError(f"JSON 请求体超过 {format_bytes(limit)} 上限", 413)
    raw = request.get_data(cache=True)
    if not raw:
        if optional:
            return {}
        raise ApiInputError("请求体不能为空", 400)
    if len(raw) > limit:
        raise ApiInputError(f"JSON 请求体超过 {format_bytes(limit)} 上限", 413)
    mimetype = (request.mimetype or "").lower()
    if mimetype != "application/json" and not mimetype.endswith("+json"):
        raise ApiInputError("请求体必须是 application/json", 415)
    try:
        payload = json.loads(raw.decode("utf-8-sig"))
    except (UnicodeDecodeError, ValueError):
        raise ApiInputError("请求体不是合法的 JSON", 400)
    if not isinstance(payload, dict):
        raise ApiInputError("请求体必须是 JSON 对象", 400)
    return payload


def _json_error(message: str, status: int = 400, **extra: Any):
    payload = {"error": message, **extra}
    return jsonify(payload), status


def _bool(value: Any, default: bool = False) -> bool:
    if value is None:
        return default
    if isinstance(value, bool):
        return value
    return str(value).lower() in ("1", "true", "yes", "on", "是")


def _query_int(name: str, default: int, *, minimum: int = 0, maximum: int | None = None) -> int:
    """Read an integer query parameter with explicit 400 semantics."""
    raw = request.args.get(name)
    if raw is None or not str(raw).strip():
        return default
    try:
        value = int(str(raw).strip())
    except (TypeError, ValueError):
        raise ApiInputError(f"{name} 必须是整数")
    if value < minimum:
        raise ApiInputError(f"{name} 不能小于 {minimum}")
    if maximum is not None and value > maximum:
        return maximum
    return value


def _safe_upload_name(name: str) -> str:
    """Keep a GACOS upload name, stripping directories and unsafe characters."""
    base = Path(str(name or "").replace("\\", "/")).name
    base = re.sub(r"[^A-Za-z0-9._-]+", "_", base).strip("._")
    return base or "upload.bin"


def _list_field(value: Any, *, newline_only: bool = False) -> list[str]:
    """Normalise a JSON array or a textarea string into a list of strings."""
    if value is None:
        return []
    if isinstance(value, (list, tuple, set)):
        return [str(item).strip() for item in value if str(item).strip()]
    text = str(value).replace("\r", "\n")
    parts = text.split("\n") if newline_only else re.split(r"[\s,;]+", text)
    return [part.strip() for part in parts if part.strip()]


def _stack_n_dates(root: Path) -> int | None:
    meta = read_json(root / "data" / "stack" / "meta.json", {}) or {}
    try:
        value = int(meta.get("n_dates") or 0)
    except (TypeError, ValueError):
        return None
    return value or None


def _busy_response(job: dict[str, Any]):
    return _json_error(
        f"该项目已有任务在运行：{job.get('label') or job.get('kind') or job.get('id')}",
        409,
        job=job,
    )


def _ensure_idle(jobs: JobManager, project_id: str):
    active = jobs.active(project_id)
    if active:
        return _busy_response(active[0])
    return None


def _package_version(name: str) -> str | None:
    try:
        module = __import__(name)
        return getattr(module, "__version__", "installed")
    except Exception:
        return None


def _doctor() -> dict[str, Any]:
    checks = []
    checks.append({"name": "Python", "ok": sys.version_info >= (3, 9), "value": platform.python_version()})
    for package in ("numpy", "scipy", "matplotlib", "skimage", "flask", "tifffile", "docx"):
        version = _package_version(package)
        checks.append({"name": package, "ok": version is not None, "value": version or "未安装"})
    snaphu = shutil.which("snaphu")
    checks.append({"name": "SNAPHU（可选）", "ok": bool(snaphu), "value": snaphu or "未安装 · 使用内置解缠"})
    try:
        WORKSPACE_DIR.mkdir(parents=True, exist_ok=True)
        probe = WORKSPACE_DIR / ".write_test"
        probe.write_text("ok", encoding="utf-8")
        probe.unlink()
        writable = True
    except Exception as exc:
        writable = False
        checks.append({"name": "工作区写入", "ok": False, "value": str(exc)})
    if writable:
        checks.append({"name": "工作区写入", "ok": True, "value": str(WORKSPACE_DIR)})
    free = shutil.disk_usage(WORKSPACE_DIR).free if WORKSPACE_DIR.exists() else 0
    checks.append({"name": "可用磁盘", "ok": free > 500 * 1024 * 1024, "value": format_bytes(free)})
    return {
        "version": __version__,
        "platform": platform.platform(),
        "workspace": str(WORKSPACE_DIR),
        "checks": checks,
        "ok": all(c["ok"] for c in checks if c["name"] not in ("SNAPHU（可选）",)),
    }


